//! Raw HLSL extension shaders (`.hlsl`, the port path for OBS shader-filter code, `docs/EXTENSIONS.md` 4.3 and open
//! question 8).
//!
//! The author writes `float4 main(float4 pos : SV_Position) : SV_Target`. The app puts a generated prelude in front
//! of the file with the same names and registers as the WGSL convention (`frame` at `b0`, `params` at `b1`, `image`
//! and `history` at `t0` and `t1`, the `path` images at `t2..t5`, `smp` at `s0`, and the helpers `tex`, `texel`,
//! `to_linear`, `to_srgb`, `luma`, `hash`), and FXC compiles it with `ps_5_0`.
//!
//! HLSL packs a constant buffer by its own rules, which differ from WGSL's (`docs/SPIKE-EXT.md` 4), so the offsets
//! are not computed here: they are read from the compiled bytecode with `D3DReflect`. Nothing in this path is checked
//! by `naga`: there is no inlining limit (FXC inlines every call) and no `check_cost`; the only guards are the source
//! size, a nesting limit and the bounded worker with its timeout (`ext::run_bounded`). `#include` finds no handler
//! and fails, so a shader cannot read files.

use windows::core::{Interface, PCSTR};
use windows::Win32::Graphics::Direct3D::Fxc::D3DReflect;
use windows::Win32::Graphics::Direct3D11::{
    ID3D11ShaderReflection, D3D11_SHADER_BUFFER_DESC, D3D11_SHADER_TYPE_DESC, D3D11_SHADER_VARIABLE_DESC,
};

use super::compile::compile_hlsl;
use super::layout::{Layout, Member, ScalarKind, UType};
use super::wgsl::{
    normalize_type, ParamDecl, TextureSlot, Translated, BINDING_HISTORY, BINDING_IMAGE, BINDING_PATH_FIRST,
    FRAME_MEMBERS, MAX_PATH_IMAGES, MAX_SOURCE_BYTES,
};
use super::ExtError;

/// Brackets (`(`, `[`, `{`) nested deeper than this are refused before FXC sees the source.
pub const MAX_NESTING: usize = 256;

/// The generated lines before the author's code (and the first line of the author's code, 1-based).
pub struct Prelude {
    pub text: String,
    pub author_line: u32,
}

const HELPERS: &str = "\
SamplerState smp : register(s0);
float4 tex(Texture2D<float4> t, float2 uv) { return t.SampleLevel(smp, uv, 0); }
float4 texel(Texture2D<float4> t, int2 p) { return t.Load(int3(p, 0)); }
float3 to_linear(float3 c) {
  float3 x = max(c, 0.0);
  return lerp(pow((x + 0.055) / 1.055, 2.4), x / 12.92, step(x, 0.04045));
}
float3 to_srgb(float3 c) {
  float3 x = saturate(c);
  return lerp(1.055 * pow(x, 1.0 / 2.4) - 0.055, x * 12.92, step(x, 0.0031308));
}
float luma(float3 c) { return dot(c, float3(0.2126, 0.7152, 0.0722)); }
float hash(float2 p) { return frac(sin(dot(p, float2(12.9898, 78.233))) * 43758.5453); }
// ---- end of prelude ----
";

fn hlsl_type(ty: &str) -> Result<&'static str, ExtError> {
    Ok(match normalize_type(ty).as_str() {
        "f32" => "float",
        "i32" => "int",
        "u32" => "uint",
        "vec2<f32>" => "float2",
        "vec3<f32>" => "float3",
        "vec4<f32>" => "float4",
        other => return Err(ExtError::manifest(format!("`{other}` is not a type an .hlsl shader's params can have"))),
    })
}

/// The `UType` of a type the prelude declares.
fn utype(ty: &str) -> Option<UType> {
    Some(match normalize_type(ty).as_str() {
        "f32" => UType::Scalar(ScalarKind::F32),
        "i32" => UType::Scalar(ScalarKind::I32),
        "u32" => UType::Scalar(ScalarKind::U32),
        "vec2<f32>" => UType::Vector { n: 2, kind: ScalarKind::F32 },
        "vec3<f32>" => UType::Vector { n: 3, kind: ScalarKind::F32 },
        "vec4<f32>" => UType::Vector { n: 4, kind: ScalarKind::F32 },
        _ => return None,
    })
}

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_alphabetic())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// The prelude for these params and images.
pub fn prelude(params: &[ParamDecl], images: &[&str]) -> Result<Prelude, ExtError> {
    if images.len() > MAX_PATH_IMAGES {
        return Err(ExtError::manifest(format!("{} image params, at most {MAX_PATH_IMAGES} are supported", images.len())));
    }
    let reserved = ["frame", "params", "image", "history", "smp"];
    for name in params.iter().map(|p| p.name.as_str()).chain(images.iter().copied()) {
        if !is_ident(name) || name.starts_with('_') {
            return Err(ExtError::manifest(format!("`{name}` is not a valid parameter name")));
        }
    }
    for name in images {
        if reserved.contains(name) {
            return Err(ExtError::manifest(format!("image param `{name}` clashes with a built-in name")));
        }
    }
    let mut text = String::from("// ---- generated by Better Cam, extension API 1 (HLSL) ----\nstruct FrameData {\n");
    for (name, ty) in FRAME_MEMBERS {
        text.push_str(&format!("  {} {name};\n", hlsl_type(ty)?));
    }
    text.push_str("};\ncbuffer Frame : register(b0) { FrameData frame; };\n");
    if !params.is_empty() {
        text.push_str("struct ParamsData {\n");
        for p in params {
            text.push_str(&format!("  {} {};\n", hlsl_type(&p.ty)?, p.name));
        }
        text.push_str("};\ncbuffer Params : register(b1) { ParamsData params; };\n");
    }
    text.push_str("Texture2D<float4> image : register(t0);\nTexture2D<float4> history : register(t1);\n");
    for (i, name) in images.iter().enumerate() {
        text.push_str(&format!("Texture2D<float4> {name} : register(t{});\n", 2 + i));
    }
    text.push_str(HELPERS);
    Ok(Prelude { author_line: text.lines().count() as u32 + 1, text })
}

/// Brackets nested deeper than [`MAX_NESTING`], ignoring comments and strings only roughly (a bracket inside a comment
/// counts): the limit is a guard, not a parser.
fn check_nesting(source: &str) -> Result<(), ExtError> {
    let (mut depth, mut line) = (0usize, 1u32);
    for c in source.chars() {
        match c {
            '(' | '[' | '{' => {
                depth += 1;
                if depth > MAX_NESTING {
                    return Err(ExtError::source_at(line, 1, format!("brackets are nested more than {MAX_NESTING} deep")));
                }
            }
            ')' | ']' | '}' => depth = depth.saturating_sub(1),
            '\n' => line += 1,
            _ => {}
        }
    }
    Ok(())
}

/// Compile an `.hlsl` author file with the generated prelude. Returns the translation (its `hlsl` is the full text
/// FXC saw, the layouts are read from the bytecode) and the `ps_5_0` bytecode. Runs FXC on a bounded worker.
pub fn translate_hlsl(
    source: &str,
    params: &[ParamDecl],
    images: &[&str],
) -> Result<(Translated, Vec<u8>), ExtError> {
    let source = source.strip_prefix('\u{feff}').unwrap_or(source);
    if source.len() > MAX_SOURCE_BYTES {
        return Err(ExtError::source(format!(
            "the shader is {} bytes, the limit is {MAX_SOURCE_BYTES} bytes",
            source.len()
        )));
    }
    check_nesting(source)?;
    let pre = prelude(params, images)?;
    let full = format!("{}{}", pre.text, source);
    let code = compile_hlsl(&full, pre.author_line)?;

    let frame_members: Vec<(String, UType)> = FRAME_MEMBERS
        .iter()
        .map(|(n, t)| (n.to_string(), utype(t).expect("frame member types are known")))
        .collect();
    let param_members: Vec<(String, UType)> = params
        .iter()
        .map(|p| utype(&p.ty).map(|t| (p.name.clone(), t)).ok_or_else(|| ExtError::manifest(format!("parameter `{}`: unsupported type", p.name))))
        .collect::<Result<_, _>>()?;
    let frame = reflect_cbuffer(&code, "Frame", "Frame", &frame_members)?;
    let params_layout = if params.is_empty() { None } else { reflect_cbuffer(&code, "Params", "Params", &param_members)? };

    let mut textures = vec![
        TextureSlot { name: "image".into(), binding: BINDING_IMAGE, register: 0 },
        TextureSlot { name: "history".into(), binding: BINDING_HISTORY, register: 1 },
    ];
    for (i, name) in images.iter().enumerate() {
        textures.push(TextureSlot { name: name.to_string(), binding: BINDING_PATH_FIRST + i as u32, register: 2 + i as u32 });
    }
    Ok((Translated { hlsl: full, frame, params: params_layout, textures, uses_sampler: true }, code))
}

/// The layout of the constant buffer `cbuffer` (holding one struct variable) as FXC placed it. `None` when the shader
/// never reads it (FXC drops a constant buffer nothing uses; there is then nothing to bind).
fn reflect_cbuffer(
    code: &[u8],
    cbuffer: &str,
    name: &str,
    members: &[(String, UType)],
) -> Result<Option<Layout>, ExtError> {
    let fail = |what: &str, e: windows::core::Error| ExtError::internal(format!("reading the compiled shader ({what}): {e}"));
    // SAFETY: plain reflection calls on bytecode FXC just produced; the descriptor structs and the name are locals
    // that outlive the calls, and the reflection interfaces are released when they drop.
    unsafe {
        let mut raw: *mut std::ffi::c_void = std::ptr::null_mut();
        D3DReflect(code.as_ptr() as *const _, code.len(), &ID3D11ShaderReflection::IID, &mut raw)
            .map_err(|e| fail("D3DReflect", e))?;
        let refl: ID3D11ShaderReflection = ID3D11ShaderReflection::from_raw(raw);
        let c_name = std::ffi::CString::new(cbuffer).map_err(|_| ExtError::internal("constant buffer name"))?;
        let Some(cb) = refl.GetConstantBufferByName(PCSTR(c_name.as_ptr() as *const u8)) else {
            return Ok(None);
        };
        let mut desc = D3D11_SHADER_BUFFER_DESC::default();
        if cb.GetDesc(&mut desc).is_err() {
            // The reflection's "null" buffer: the shader does not use it.
            return Ok(None);
        }
        let Some(var) = cb.GetVariableByIndex(0) else { return Ok(None) };
        let mut vdesc = D3D11_SHADER_VARIABLE_DESC::default();
        var.GetDesc(&mut vdesc).map_err(|e| fail("variable", e))?;
        let Some(ty) = var.GetType() else { return Ok(None) };
        let mut tdesc = D3D11_SHADER_TYPE_DESC::default();
        ty.GetDesc(&mut tdesc).map_err(|e| fail("type", e))?;
        let mut offsets: Vec<(String, u32)> = Vec::new();
        for i in 0..tdesc.Members {
            let Some(mty) = ty.GetMemberTypeByIndex(i) else { continue };
            let mut md = D3D11_SHADER_TYPE_DESC::default();
            mty.GetDesc(&mut md).map_err(|e| fail("member", e))?;
            let mname = ty.GetMemberTypeName(i);
            offsets.push((mname.to_string().unwrap_or_default(), vdesc.StartOffset + md.Offset));
        }
        let mut out = Vec::new();
        for (member, ty) in members {
            let offset = offsets
                .iter()
                .find(|(n, _)| n == member)
                .map(|(_, o)| *o)
                .ok_or_else(|| ExtError::internal(format!("the compiled shader has no member `{member}` in its {cbuffer} buffer")))?;
            out.push(Member { name: member.clone(), offset, ty: ty.clone() });
        }
        Ok(Some(Layout { name: name.to_string(), size: desc.Size, members: out }))
    }
}
